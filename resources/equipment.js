const equipmentLabel = (record) => {
  const name = [record.make, record.model].filter(Boolean).join(' ');
  const tag = record.id_number || record.serial;
  if (name && tag) {
    return `${name} (${tag})`;
  }
  return name || tag || `Equipment ${record.id}`;
};

